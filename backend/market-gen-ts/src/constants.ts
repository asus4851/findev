// ── Константи моделі ціни ────────────────────────────────────────────

// Зсув ціни після вичерпання рівня, у базисних пунктах (1 б.п. = 0,01%).
export const PRICE_SHIFT_MIN_BP = 5;       // 0,05%
export const PRICE_SHIFT_MAX_BP = 15;      // 0,15%
export const BASIS_POINTS = 10000;         // 100% у базисних пунктах

// Мінімальний зсув і мінімальна ціна, у центах.
export const PRICE_SHIFT_MIN_CENTS = 1;    // щоб на дешевих інструментах ціна не застрягала
export const MIN_PRICE_CENTS = 1;          // ціна завжди додатна

// Верхня межа опорної ціни: $1 000 000.00.
// Обрано так, щоб в AssemblyScript усі обчислення вміщалися в i32 (максимум ≈ 2,1 млрд):
// найбільший добуток price × basisPoints = 100 000 000 × 15 = 1,5 млрд.
export const MAX_PRICE_CENTS = 100_000_000;

// Відступ ask вгору і bid вниз від ціни квоти, окремо для кожного боку,
// у базисних пунктах (1 б.п. = 0,01%). Для ціни $100 це 1..5 центів на бік.
export const SPREAD_DELTA_MIN_BP = 1;      // 0,01%
export const SPREAD_DELTA_MAX_BP = 5;      // 0,05%

// Мінімальний відступ у центах: на дешевих інструментах відсоток округлюється до 0,
// і без цього bid зрівнявся б з ask.
export const SPREAD_DELTA_MIN_CENTS = 1;

// Діапазон початкової ціни інструмента, у центах: $50.00..$300.00.
// Різні інструменти стартують з різних цін.
export const START_PRICE_MIN_CENTS = 5000;
export const START_PRICE_MAX_CENTS = 30000;

