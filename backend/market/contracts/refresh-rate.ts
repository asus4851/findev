// Частота обновления таблицы: как часто воркер отправляет снимок метрик в Angular.
//
// Это настройка клиента, а не продюсера, поэтому её нет среди трёх настроек из ТЗ:
// она не перезапускает генерацию и не влияет на метрики. Воркер, как сервер рыночных данных,
// учитывает каждую сделку, но клиенту отдаёт сводный снимок не чаще выбранного интервала.

// Без ограничения: снимок после каждого батча. Режим производительности, только для теста.
export const REFRESH_UNLIMITED = 0;

// Интервал по умолчанию, мс.
export const REFRESH_DEFAULT_MS = 500;

// Варианты для переключателя на дашборде, мс: 0,5 с, 1 с, 5 с и режим без ограничения.
export const REFRESH_OPTIONS_MS = [500, 1000, 5000, REFRESH_UNLIMITED];
