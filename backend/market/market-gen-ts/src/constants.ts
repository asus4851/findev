// ── Константы модели цены ────────────────────────────────────────────

// Сдвиг цены после исчерпания уровня, в базисных пунктах (1 б.п. = 0,01%).
export const PRICE_SHIFT_MIN_BP = 5;       // 0,05%
export const PRICE_SHIFT_MAX_BP = 15;      // 0,15%
export const BASIS_POINTS = 10000;         // 100% в базисных пунктах

// Минимальный сдвиг и минимальная цена, в центах.
export const PRICE_SHIFT_MIN_CENTS = 1;    // чтобы на дешёвых инструментах цена не застревала
export const MIN_PRICE_CENTS = 1;          // цена всегда положительна

// Верхняя граница опорной цены: $1 000 000.00.
// Выбрана так, чтобы в AssemblyScript все вычисления помещались в i32 (максимум ≈ 2,1 млрд):
// наибольшее произведение price × basisPoints = 100 000 000 × 15 = 1,5 млрд.
export const MAX_PRICE_CENTS = 100_000_000;

// Отступ ask вверх и bid вниз от цены котировки, отдельно для каждой стороны,
// в базисных пунктах (1 б.п. = 0,01%). Для цены $100 это 1..5 центов на сторону.
export const SPREAD_DELTA_MIN_BP = 1;      // 0,01%
export const SPREAD_DELTA_MAX_BP = 5;      // 0,05%

// Минимальный отступ в центах: на дешёвых инструментах процент округляется до 0,
// и без этого bid сравнялся бы с ask.
export const SPREAD_DELTA_MIN_CENTS = 1;

// Диапазон начальной цены инструмента, в центах: $50.00..$300.00.
// Разные инструменты стартуют с разных цен.
export const START_PRICE_MIN_CENTS = 5000;
export const START_PRICE_MAX_CENTS = 30000;

// ── Константы количеств ──────────────────────────────────────────────

// Количество на уровне стакана (bid и ask) после перекотировки, в штуках. Использует getQty.
export const minQty = 10;
export const maxQty = 1000;

// Размер рыночного ордера, в штуках. Использует getOrderQty.
// Минимум 1 гарантирует положительное количество сделки. Ордер значительно меньше уровня,
// поэтому уровень исчерпывается лишь после нескольких сделок, и цена движется плавно.
export const minOrderQty = 1;
export const maxOrderQty = 100;
